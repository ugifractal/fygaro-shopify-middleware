# frozen_string_literal: true

require "base64"
require "json"
require "openssl"

module Fygaro
  # Creates a Fygaro hosted checkout session by minting a signed JWT and
  # redirecting the buyer to a Fygaro Link. The JWT locks the checkout amount
  # so the buyer cannot edit it.
  #
  # Configure with FYGARO_PAYMENT_LINK_URL (the shareable Fygaro Link URL) and
  # the signing credentials FYGARO_API_KEY (the JWT `kid`) and
  # FYGARO_API_SECRET (the HMAC secret).
  class Gateway
    class NotConfigured < StandardError; end
    class Error < StandardError; end

    Session = Struct.new(:session_id, :redirect_url, keyword_init: true)

    PAYLOAD_TTL_SECONDS = 900 # 15 minutes

    def self.create_session(payload)
      new.create_session(payload)
    end

    def create_session(payload)
      link_url = ENV.fetch("FYGARO_PAYMENT_LINK_URL") do
        raise NotConfigured, "FYGARO_PAYMENT_LINK_URL is not configured"
      end
      api_key = ENV.fetch("FYGARO_API_KEY") { raise NotConfigured, "FYGARO_API_KEY is not configured" }
      api_secret = ENV.fetch("FYGARO_API_SECRET") { raise NotConfigured, "FYGARO_API_SECRET is not configured" }

      # The caller passes the Shopify total in the store's money (IDR minor
      # units). Fygaro does not support IDR, so convert to USD minor units and
      # charge in USD. `amount` is then a decimal string (up to 2 dp).
      usd_minor = Fygaro::Fx.idr_to_usd_minor(payload.fetch(:total_amount))
      amount = format("%.2f", usd_minor / 100.0)

      header = { alg: "HS256", typ: "JWT", kid: api_key }
      raw_token = payload.fetch(:cart_token).to_s
      # Random opaque reference (generated by the caller) so the Fygaro-visible
      # custom_reference is always <= 40 chars and doesn't leak the Shopify GID
      # token. The webhook echoes it back to correlate to the FygaroCheckout.
      custom_reference = payload.fetch(:custom_reference)
      claims = {
        amount: amount,
        currency: "USD",
        custom_reference: custom_reference,
        exp: Time.now.to_i + PAYLOAD_TTL_SECONDS
      }

      encoded_header = base64_url_json(header)
      encoded_claims = base64_url_json(claims)
      signature = OpenSSL::HMAC.digest("SHA256", api_secret, "#{encoded_header}.#{encoded_claims}")
      encoded_signature = Base64.urlsafe_encode64(signature, padding: false)

      jwt = "#{encoded_header}.#{encoded_claims}.#{encoded_signature}"
      # session_id keeps the full Shopify token for correlation; the JWT
      # custom_reference is the random token generated by the caller.
      Session.new(session_id: raw_token, redirect_url: "#{link_url}?jwt=#{jwt}")
    end

    private

    def base64_url_json(value)
      Base64.urlsafe_encode64(JSON.generate(value), padding: false)
    end
  end
end
